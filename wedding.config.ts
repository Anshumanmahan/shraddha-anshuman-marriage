/**
 * wedding.config.ts
 * ------------------------------------------------------------------
 * SINGLE SOURCE OF TRUTH for every piece of wedding content.
 *
 * Everything factual (names, dates, venues, timings, family names) is
 * transcribed from the supplied invitation and must not be altered
 * without an updated document.
 *
 * Anything still unknown is typed as `null` and rendered as an elegant
 * placeholder — never as invented content.
 * ------------------------------------------------------------------
 */

import { generatedAssets, generatedTracks } from "@/data/generated-assets";

export type EventIcon =
  | "rings"
  | "sangeet"
  | "dinner"
  | "haldi"
  | "barat"
  | "jaimaal"
  | "reception";

export interface WeddingEvent {
  /** Stable key used for animation + anchors. */
  id: string;
  /** Factual event name — from the invitation. */
  title: string;
  /** Factual time — from the invitation. Empty string when not specified. */
  time: string;
  /** Factual sub-location, e.g. "At Poolside". */
  subtitle?: string;
  /** Optional host-written flavour copy. `null` until supplied. */
  description?: string | null;
  icon: EventIcon;
  /** Path under /public/assets/events/. `null` renders a placeholder frame. */
  image?: string | null;
}

export type VenueId = "agra";

export interface WeddingDay {
  id: string;
  /** Design copy — the chapter heading for this day. */
  chapter: string;
  /** Design copy — one line of atmosphere for the chapter. */
  chapterLine: string;
  /** Factual date, formatted for display. */
  date: string;
  /** Short form used on timeline markers. */
  dateShort: string;
  /** Machine-readable date. */
  isoDate: string;
  /** Key into `venues`. */
  venueId: VenueId;
  events: WeddingEvent[];
}

export interface Venue {
  id: VenueId;
  name: string;
  address: string;
  city: string;
  /**
   * Paste the exact share link from Google Maps here when available.
   * While `null`, the UI falls back to a Google Maps *search* for
   * name + address rather than inventing a place URL.
   */
  googleMapsUrl: string | null;
  /** Photograph of the venue. `null` renders an ornamental placeholder. */
  image: ImageAsset | null;
}

/** A bitmap with its intrinsic size, so nothing ever shifts while loading. */
export interface ImageAsset {
  src: string;
  width: number;
  height: number;
  /** Inline preview, generated by `npm run assets`. */
  blurDataURL?: string;
  alt?: string;
}

export interface Person {
  name: string;
  parents: string;
  /** "S/O" or "D/O" — set per person rather than assumed from the role. */
  parentsPrefix: string;
  /** Listed above the parents on the card, senior generation first. */
  grandparents: { prefix: string; names: string }[];
  /**
   * The illustrated full-length avatar. Sized by height wherever it is
   * used, so bride and groom always stand at the same scale.
   * `null` falls back to drawn line art.
   */
  avatar: ImageAsset | null;
  /** Photograph under /public/assets/bride|groom/. `null` uses the avatar. */
  portrait: string | null;
}

