export type WeddingConfig = typeof weddingConfig;

/* ------------------------------------------------------------------ */
/* Derived helpers — keep components free of lookup logic.             */
/* ------------------------------------------------------------------ */

export const getVenue = (id: VenueId): Venue => weddingConfig.venues[id];

export const venueList: Venue[] = [
  weddingConfig.venues.agra,
];

/** Days happening at a venue, for the venue card's "what happens here". */
export const daysAtVenue = (id: VenueId): WeddingDay[] =>
  weddingConfig.days.filter((day) => day.venueId === id);

/**
 * A Google Maps destination for a venue. Uses the supplied share link when
 * one exists; otherwise builds a Google Maps *search* from the venue name
 * and address rather than guessing at a place URL.
 */
export const venueMapsUrl = (venue: Venue): string =>
  venue.googleMapsUrl ??
  `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
    `${venue.name}, ${venue.address}`,
  )}`;

/** Countdown target as an absolute instant, anchored to the wedding's zone. */
export const countdownTargetMs = Date.parse(
  `${weddingConfig.countdownTarget}${weddingConfig.countdownTimeZoneOffset}`,
);
